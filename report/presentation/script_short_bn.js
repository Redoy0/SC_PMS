const BN_DIGITS = "০১২৩৪৫৬৭৮৯";
const bn = (s) => String(s).replace(/[0-9]/g, (d) => BN_DIGITS[d]);

function notesFor(i) {
  const s = slides[i];
  let t = `স্লাইড ${bn(s.n)} / ${bn(slides.length)}   (প্রায় ${bn(s.time)} মিনিট)\n\nবলুন:\n` + s.say.join("\n\n");
  if (s.show) t += `\n\nদেখান: ${s.show}`;
  return t;
}

