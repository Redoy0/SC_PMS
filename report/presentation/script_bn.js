const BN_DIGITS = "০১২৩৪৫৬৭৮৯";
const bn = (s) => String(s).replace(/[0-9]/g, (d) => BN_DIGITS[d]);

function notesFor(i) {
  const s = slides[i];
  const who = s.speaker === "Both" ? "শারমিন ও তাসনিম" : NAME[s.speaker];
  let t = `বক্তা: ${who}   (প্রায় ${bn(s.time)} মিনিট)\n\nবলুন:\n` +
    s.say.map((p) => p.replace(/^(Sharmin|Tasnim):\s*/, (m, n) => NAME[n] + ": ")).join("\n\n");
  if (s.show) t += `\n\nদেখান: ${s.show}`;
  if (s.handover) t += `\n\nহস্তান্তর: ${s.handover}`;
  return t;
}

