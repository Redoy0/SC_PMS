/*
 * Generates LaTeX tables for the report directly from results.json, so the
 * numbers printed in Chapter 5 and Appendix A cannot drift from the evidence.
 * Usage: node make-tables.cjs results.json ../../tables
 */
'use strict';
const fs = require('fs');
const path = require('path');

const [, , inFile = path.join(__dirname, 'results.json'), outDir = path.join(__dirname, '../../tables')] = process.argv;
const data = JSON.parse(fs.readFileSync(inFile, 'utf8'));
fs.mkdirSync(outDir, { recursive: true });

const esc = (s) => String(s)
	.replace(/\\/g, '\\textbackslash{}')
	.replace(/([#$%&_{}])/g, '\\$1')
	.replace(/~/g, '\\textasciitilde{}')
	.replace(/\^/g, '\\textasciicircum{}')
	.replace(/</g, '\\textless{}')
	.replace(/>/g, '\\textgreater{}')
	.replace(/"/g, "''");
// Same, plus permitted line breaks after punctuation so long codes/JSON fit narrow cells
const escb = (s) => esc(s).replace(/(\\_|[,;:=\/])/g, '$1\\allowbreak{}');

// ---- Full test-case table (Appendix A) ----
let full = `% Generated by report/evidence/api-test/make-tables.cjs from results.json -- do not edit by hand
\\begin{scriptsize}
\\begin{longtable}{@{}P{0.6cm}P{1.5cm}P{3.7cm}P{3.0cm}P{3.3cm}P{0.8cm}@{}}
\\caption[Executed black-box test cases and observed results]{Executed black-box test cases and observed results (generated from \\code{results.json})}\\label{tab:all-tests}\\\\
\\toprule
\\textbf{ID} & \\textbf{Req.} & \\textbf{Test case} & \\textbf{Expected} & \\textbf{Observed} & \\textbf{Status} \\\\
\\midrule
\\endfirsthead
\\toprule
\\textbf{ID} & \\textbf{Req.} & \\textbf{Test case} & \\textbf{Expected} & \\textbf{Observed} & \\textbf{Status} \\\\
\\midrule
\\endhead
\\bottomrule
\\endfoot
`;
for (const r of data.results) {
	const finding = /finding/i.test(r.requirement);
	const status = r.status === 'Pass' ? (finding ? 'Pass$^{\\dagger}$' : 'Pass') : '\\textbf{Fail}';
	full += `${r.id} & ${escb(r.requirement)} & ${esc(r.title)} & ${escb(r.expected)} & ${escb(r.actual)} & ${status} \\\\\n`;
}
full += `\\end{longtable}
\\end{scriptsize}
\\noindent{\\footnotesize $^{\\dagger}$\\,T56 confirms documented behaviour (forward skips are allowed); it is reported as a design finding rather than as evidence of correctness.}
`;
fs.writeFileSync(path.join(outDir, 'test-cases.tex'), full);

// ---- Summary by area (Chapter 5) ----
const order = ['System', 'Robustness', 'Auth', 'Users', 'Access control', 'Booking', 'Parcels', 'Tracking', 'Assignment', 'Lifecycle', 'Real-time', 'Analytics', 'Reports', 'Security'];
const by = {};
for (const r of data.results) {
	by[r.area] = by[r.area] || { n: 0, pass: 0, ids: [] };
	by[r.area].n++; if (r.status === 'Pass') by[r.area].pass++; by[r.area].ids.push(r.id);
}
let sum = `% Generated by report/evidence/api-test/make-tables.cjs from results.json -- do not edit by hand
\\begin{table}[htbp]
\\centering
\\caption{Summary of executed black-box tests by area}
\\label{tab:test-summary}
\\small
\\begin{tabularx}{\\textwidth}{@{}P{3.0cm}rrL@{}}
\\toprule
\\textbf{Area} & \\textbf{Tests} & \\textbf{Passed} & \\textbf{Test IDs} \\\\
\\midrule
`;
const areas = [...order.filter(a => by[a]), ...Object.keys(by).filter(a => !order.includes(a))];
for (const a of areas) sum += `${esc(a)} & ${by[a].n} & ${by[a].pass} & ${by[a].ids.join(', ')} \\\\\n`;
sum += `\\midrule
\\textbf{Total} & \\textbf{${data.summary.total}} & \\textbf{${data.summary.passed}} & \\\\
\\bottomrule
\\end{tabularx}
\\end{table}
`;
fs.writeFileSync(path.join(outDir, 'test-summary.tex'), sum);

// ---- Latency table (Chapter 5) ----
const p = data.performance;
let lat = `% Generated by report/evidence/api-test/make-tables.cjs from results.json -- do not edit by hand
\\begin{table}[htbp]
\\centering
\\caption{Locally measured latencies (sequential requests, loop-back interface, in-memory database)}
\\label{tab:latency}
\\small
\\begin{tabularx}{\\textwidth}{@{}Lrrrrr@{}}
\\toprule
\\textbf{Measurement (ms)} & \\textbf{n} & \\textbf{Mean} & \\textbf{Median} & \\textbf{P95} & \\textbf{Max} \\\\
\\midrule
`;
for (const [k, v] of Object.entries(p.httpLatencyMs)) lat += `HTTP round trip: \\texttt{${esc(k)}} & ${v.n} & ${v.mean} & ${v.median} & ${v.p95} & ${v.max} \\\\\n`;
const s = p.socketAgentLocationToAdminMs;
lat += `Socket: agent emit $\\rightarrow$ admin receives \\texttt{agent:location:update} & ${s.n} & ${s.mean} & ${s.median} & ${s.p95} & ${s.max} \\\\\n`;
lat += `\\midrule
\\multicolumn{6}{@{}L@{}}{Status request issued $\\rightarrow$ owner socket has \\texttt{parcel:update} (includes the HTTP round trip): ${p.statusChangeToOwnerSocketMs.samples.join(', ')}\\,ms (3 samples)} \\\\
\\bottomrule
\\end{tabularx}
\\end{table}
`;
fs.writeFileSync(path.join(outDir, 'latency.tex'), lat);
console.log('tables written to', outDir, data.summary);
